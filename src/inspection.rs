use std::io::{Write, stdin, stdout};

use termion::{event::Key, input::TermRead, raw::IntoRawMode};

use crate::tui::{
    background::{BACKGROUND_COLOR, colored_background},
    grid::GRID_HEIGHT,
};

pub struct Inspection {
    pub name: String,
    pub description: String,
    pub detail_view: String,
}

impl Inspection {
    pub fn start_inspection(&self) {
        let title_line = format!(
            "{}{}{} - {}{}",
            termion::cursor::Goto(1, 1),
            termion::color::Bg(BACKGROUND_COLOR),
            self.name,
            self.description,
            termion::color::Bg(termion::color::Reset)
        );

        let key_binding_info_line = format!(
            "{}{}<backspace>{}",
            termion::color::Bg(BACKGROUND_COLOR),
            termion::cursor::Goto(1, (GRID_HEIGHT + 2) as u16),
            termion::color::Bg(termion::color::Reset),
        );

        // draw the inspection view on screen
        let mut stdout = stdout().into_raw_mode().unwrap();
        write!(
            stdout,
            "{}{}{}{}{}{}",
            termion::clear::All,
            colored_background(),
            title_line,
            self.detail_view,
            key_binding_info_line,
            termion::cursor::Hide,
        )
        .unwrap();
        stdout.flush().unwrap();

        // wait for key press to return
        for k in stdin().keys() {
            match k.as_ref().unwrap() {
                Key::Backspace => return,
                _ => continue,
            }
        }
    }
}

